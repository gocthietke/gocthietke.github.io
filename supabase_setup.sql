-- Compatible with the current public.posts table (9 original columns).
-- This script ADDS columns/tables and replaces policies; it does not delete posts.
-- Before running: export/backup your Supabase database.
-- Admin email must match config.js: nhunhu13061@gmail.com
-- ============================================================

begin;

-- 1) Add optional fields for article cards and SEO. Existing data is preserved.
alter table public.posts
  add column if not exists summary text,
  add column if not exists meta_title text,
  add column if not exists meta_description text,
  add column if not exists updated_at timestamptz default now();

-- 2) Ensure posts.id can be generated for new posts, without changing an IDENTITY column.
do $$
declare
  v_identity text;
  v_default text;
  v_has_unique boolean;
begin
  select is_identity, column_default
    into v_identity, v_default
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'posts'
    and column_name = 'id';

  if v_identity is null then
    raise exception 'Không tìm thấy public.posts.id. Dừng migration để tránh thay đổi nhầm bảng.';
  end if;

  if v_identity = 'NO' and v_default is null then
    create sequence if not exists public.posts_id_sola_seq;
    alter sequence public.posts_id_sola_seq owned by public.posts.id;
    perform setval(
      'public.posts_id_sola_seq',
      greatest(coalesce((select max(id) from public.posts), 0) + 1, 1),
      false
    );
    alter table public.posts
      alter column id set default nextval('public.posts_id_sola_seq');
  end if;

  select exists (
    select 1
    from pg_index i
    join pg_attribute a
      on a.attrelid = i.indrelid
     and a.attname = 'id'
    where i.indrelid = 'public.posts'::regclass
      and i.indisunique = true
      and i.indisvalid = true
      and i.indpred is null
      and i.indnatts = 1
      and i.indkey[0] = a.attnum
  ) into v_has_unique;

  if not v_has_unique then
    if exists (
      select id from public.posts group by id having count(*) > 1
    ) then
      raise exception 'public.posts đang có ID trùng. Hãy xử lý ID trùng trước khi tạo quan hệ sản phẩm.';
    end if;
    alter table public.posts
      add constraint posts_id_sola_unique unique (id);
  end if;
end $$;

-- 3) Multiple affiliate products can belong to one post.
create table if not exists public.post_products (
  id uuid primary key default gen_random_uuid(),
  post_id bigint not null references public.posts(id) on delete cascade,
  title text not null,
  description text,
  price text,
  image_url text,
  shopee_url text,
  tiktok_url text,
  other_url text,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists post_products_post_id_idx
  on public.post_products(post_id, sort_order);

-- 4) Affiliate click log. No visitor IP or personal information is stored.
create table if not exists public.click_events (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  product_id uuid references public.post_products(id) on delete set null,
  platform text not null default 'other',
  destination_url text,
  created_at timestamptz not null default now()
);

create index if not exists click_events_created_at_idx
  on public.click_events(created_at desc);
create index if not exists click_events_post_id_idx
  on public.click_events(post_id);

-- 5) The admin account is restricted by email in the authenticated JWT.
-- IMPORTANT: If your login email is different, change it here AND in config.js.
create or replace function public.is_sola_admin()
returns boolean
language sql
stable
as $$
  select coalesce(lower(auth.jwt() ->> 'email') = lower('nhunhu13061@gmail.com'), false);
$$;

grant execute on function public.is_sola_admin() to authenticated;

-- 6) Enable RLS. Remove old policies on posts so an older permissive policy
-- cannot accidentally leave unauthenticated insert/update/delete access open.
alter table public.posts enable row level security;
do $$
declare p record;
begin
  for p in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'posts'
  loop
    execute format('drop policy if exists %I on public.posts', p.policyname);
  end loop;
end $$;

create policy posts_public_read_published
  on public.posts for select to anon, authenticated
  using (published is true);
create policy posts_admin_read_all
  on public.posts for select to authenticated
  using (public.is_sola_admin());
create policy posts_admin_insert
  on public.posts for insert to authenticated
  with check (public.is_sola_admin());
create policy posts_admin_update
  on public.posts for update to authenticated
  using (public.is_sola_admin())
  with check (public.is_sola_admin());
create policy posts_admin_delete
  on public.posts for delete to authenticated
  using (public.is_sola_admin());

alter table public.post_products enable row level security;
drop policy if exists post_products_public_read_active on public.post_products;
drop policy if exists post_products_admin_read on public.post_products;
drop policy if exists post_products_admin_insert on public.post_products;
drop policy if exists post_products_admin_update on public.post_products;
drop policy if exists post_products_admin_delete on public.post_products;
create policy post_products_public_read_active
  on public.post_products for select to anon, authenticated
  using (
    active is true
    and exists (
      select 1 from public.posts p
      where p.id = post_products.post_id and p.published is true
    )
  );
create policy post_products_admin_read
  on public.post_products for select to authenticated
  using (public.is_sola_admin());
create policy post_products_admin_insert
  on public.post_products for insert to authenticated
  with check (public.is_sola_admin());
create policy post_products_admin_update
  on public.post_products for update to authenticated
  using (public.is_sola_admin())
  with check (public.is_sola_admin());
create policy post_products_admin_delete
  on public.post_products for delete to authenticated
  using (public.is_sola_admin());

alter table public.click_events enable row level security;
drop policy if exists click_events_public_insert_valid on public.click_events;
drop policy if exists click_events_admin_read on public.click_events;
create policy click_events_public_insert_valid
  on public.click_events for insert to anon, authenticated
  with check (
    exists (
      select 1 from public.posts p
      where p.id = click_events.post_id and p.published is true
    )
    and (
      click_events.product_id is null
      or exists (
        select 1 from public.post_products pp
        where pp.id = click_events.product_id
          and pp.post_id = click_events.post_id
          and pp.active is true
      )
    )
  );
create policy click_events_admin_read
  on public.click_events for select to authenticated
  using (public.is_sola_admin());

-- 7) Explicit grants work together with RLS (RLS still decides which rows are allowed).
revoke all on public.posts from anon;
revoke all on public.posts from authenticated;
grant select on public.posts to anon, authenticated;
grant insert, update, delete on public.posts to authenticated;

grant select on public.post_products to anon, authenticated;
grant insert, update, delete on public.post_products to authenticated;

grant insert on public.click_events to anon, authenticated;
grant select on public.click_events to authenticated;

grant usage, select on all sequences in schema public to authenticated;
grant usage, select on sequence public.click_events_id_seq to anon, authenticated;

-- 8) Keep the existing public Storage bucket named 'posts' for article images.
insert into storage.buckets (id, name, public)
values ('posts', 'posts', true)
on conflict (id) do update set public = true;

drop policy if exists sola_admin_upload_post_images on storage.objects;
drop policy if exists sola_admin_update_post_images on storage.objects;
drop policy if exists sola_admin_delete_post_images on storage.objects;
create policy sola_admin_upload_post_images
  on storage.objects for insert to authenticated
  with check (bucket_id = 'posts' and public.is_sola_admin());
create policy sola_admin_update_post_images
  on storage.objects for update to authenticated
  using (bucket_id = 'posts' and public.is_sola_admin())
  with check (bucket_id = 'posts' and public.is_sola_admin());
create policy sola_admin_delete_post_images
  on storage.objects for delete to authenticated
  using (bucket_id = 'posts' and public.is_sola_admin());

commit;

